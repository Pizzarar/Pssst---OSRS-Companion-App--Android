"""Builds every Pssst scene grid and writes the generated art sources.

    python tools/art/build_art.py

Outputs
  app/src/main/java/com/pssst/theme/art/ScenePalettes.kt   named Int ARGB materials
  app/src/main/java/com/pssst/theme/art/SceneArt.kt        generated SceneGrids
  app/src/main/res/drawable/ic_launcher_foreground.xml     crest, 3x3 viewport units / px
  app/src/main/res/drawable/ic_launcher_monochrome.xml     themed-icon silhouette
  app/src/main/res/mipmap-*/ic_launcher{,_round}.png       API 24-25 legacy icons
  build/art-preview/*.png                                  authoring previews

Grids use a per-scene legend: 'o' is always the outline, '.' is transparent.
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from PIL import Image  # noqa: E402

import crest  # noqa: E402
import preview  # noqa: E402
import scenes_b  # noqa: E402
import vignettes  # noqa: E402
from palette import PALETTE  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ART_DIR = os.path.join(ROOT, "app", "src", "main", "java", "com", "pssst", "theme", "art")
RES_DIR = os.path.join(ROOT, "app", "src", "main", "res")
PREVIEW_DIR = os.path.join(ROOT, "build", "art-preview")

FORBIDDEN = {0xFFFFFF, 0xFFFF00, 0x00FF80}
FORBIDDEN_NAME_TOKENS = ("OsrsGreen", "OsrsYellow", "OsrsWhite")
PANEL_STONE = 0x2B251D
CONTRAST_FLOOR = 1.8
LIT_SHARE = 0.6
CHAR_POOL = "abcdefghijklmnpqrstuvwxyzABCDEFGHIJKLMNPQRSTUVWXYZ0123456789#%&*+=?@^~<>!|:;,"

# Visible 24x24 zone of the 36x36 crest (adaptive-icon viewport 18..90 => px 6..29).
CREST_VIEW = (5, 6, 24, 24)


def luminance(rgb: int) -> float:
    def ch(v: int) -> float:
        c = v / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch((rgb >> 16) & 0xFF) + 0.7152 * ch((rgb >> 8) & 0xFF) + 0.0722 * ch(rgb & 0xFF)


def contrast(a: int, b: int) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def build_all():
    grids = {}
    for name, fn in scenes_b.SCENES.items():
        grids[name] = fn()
    grids["INFORMANT_CREST"] = crest.build()
    for name, fn in vignettes.VIGNETTES.items():
        grids[name] = fn()
    return grids


def validate(grids) -> list[str]:
    problems = []
    for name, value in PALETTE.items():
        if value in FORBIDDEN:
            problems.append(f"palette {name} uses a stack-count colour")
        if any(t in name for t in FORBIDDEN_NAME_TOKENS):
            problems.append(f"palette name {name} contains a guarded token")
    for gname, c in grids.items():
        counts = c.counts()
        body = sorted((n for n in counts if n != "Outline"), key=lambda n: -counts[n])
        top = body[0]
        if contrast(PALETTE[top], PANEL_STONE) < CONTRAST_FLOOR:
            problems.append(f"{gname}: dominant colour {top} below {CONTRAST_FLOOR}:1")
        total = sum(counts[n] for n in body)
        lit = sum(counts[n] for n in body if contrast(PALETTE[n], PANEL_STONE) >= CONTRAST_FLOOR)
        share = lit / total
        print(f"  {gname}: dominant {top} {contrast(PALETTE[top], PANEL_STONE):.2f}:1, lit share {share:.0%}")
        if share < LIT_SHARE:
            problems.append(f"{gname}: only {share:.0%} of body pixels clear {CONTRAST_FLOOR}:1")
    return problems


def legend_for(c) -> dict[str, str]:
    names = c.names()
    legend = {}
    pool = iter(CHAR_POOL)
    for n in names:
        legend[n] = "o" if n == "Outline" else next(pool)
    return legend


def kotlin_palettes() -> str:
    lines = [
        "// GENERATED by tools/art/build_art.py from tools/art/palette.py. Do not edit by hand.",
        "package com.pssst.theme.art",
        "",
        "/**",
        " * Named ARGB materials shared by every [SceneGrid] (empty states, crest, vignettes).",
        " *",
        " * Dark subjects always carry a lit rim or mid tone of at least 1.8:1 against panel",
        " * stone, so silhouettes never dissolve into the stone ground.",
        " */",
        "object ScenePalettes {",
    ]
    for name, value in PALETTE.items():
        lines.append(f"    val {name}: Int = 0xFF{value:06X}.toInt()")
    lines.append("}")
    return "\n".join(lines) + "\n"


def kotlin_grids(grids) -> str:
    out = [
        "// GENERATED by tools/art/build_art.py from tools/art/*.py. Do not edit by hand.",
        "package com.pssst.theme.art",
        "",
        "/**",
        " * Character-grid pixel art for empty states (48x36), the informant crest (36x36),",
        " * and the Overview vignettes (32x24). `'o'` is the outline, `'.'` is transparent.",
        " */",
        "internal object SceneArt {",
    ]
    for gname, c in grids.items():
        legend = legend_for(c)
        out.append(f"    val {gname}: SceneGrid = SceneGrid(")
        out.append("        rows = listOf(")
        for row in c.rows(legend):
            out.append(f'            "{row}",')
        out.append("        ),")
        out.append("        palette = mapOf(")
        for n, ch in legend.items():
            out.append(f"            '{ch}' to ScenePalettes.{n},")
        out.append("        )")
        out.append("    )")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def runs_to_rects(cells: set[tuple[int, int]]) -> list[tuple[int, int, int, int]]:
    """Greedy merge of a pixel set into axis-aligned rectangles."""
    remaining = set(cells)
    rects = []
    for y in range(36):
        x = 0
        while x < 36:
            if (x, y) in remaining:
                w = 1
                while (x + w, y) in remaining:
                    w += 1
                h = 1
                while all((x + i, y + h) in remaining for i in range(w)):
                    h += 1
                for j in range(h):
                    for i in range(w):
                        remaining.discard((x + i, y + j))
                rects.append((x, y, w, h))
                x += w
            else:
                x += 1
    return rects


def path_data(rects) -> str:
    return "".join(f"M{x * 3},{y * 3}h{w * 3}v{h * 3}h-{w * 3}z" for x, y, w, h in rects)


def launcher_foreground(c) -> str:
    by_colour: dict[str, set] = {}
    for y in range(c.h):
        for x in range(c.w):
            n = c.px[y][x]
            if n is not None:
                by_colour.setdefault(n, set()).add((x, y))
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by tools/art/build_art.py from SceneArt.INFORMANT_CREST (36x36 px,",
        "     3x3 viewport units per art pixel). Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    # Outline first so material pixels sit on top in z-order.
    order = sorted(by_colour, key=lambda n: (n != "Outline", n))
    for n in order:
        lines.append("    <path")
        lines.append(f'        android:fillColor="#{PALETTE[n]:06X}"')
        lines.append(f'        android:pathData="{path_data(runs_to_rects(by_colour[n]))}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


MONO_HOLES = {"Outline", "HollowDark", "StoneDeep", "ParchDeep"}


def launcher_monochrome(c) -> str:
    cells = {(x, y) for y in range(c.h) for x in range(c.w)
             if c.px[y][x] is not None and c.px[y][x] not in MONO_HOLES}
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by tools/art/build_art.py: themed-icon silhouette of the informant crest.",
        "     Outlines and shadow hollows are cut out so pillar, cowl, eyes and scroll stay",
        "     separated when Android tints the layer. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
        "    <path",
        '        android:fillColor="#FFFFFF"',
        f'        android:pathData="{path_data(runs_to_rects(cells))}" />',
        "</vector>",
    ]) + "\n"


def legacy_icons(c) -> None:
    vx, vy, vw, vh = 6, 6, 24, 24  # adaptive visible zone in art px
    bg = (0x2B, 0x23, 0x1B)
    out = (0x0C, 0x09, 0x06)
    for folder, s in (("mdpi", 2), ("hdpi", 3), ("xhdpi", 4), ("xxhdpi", 6), ("xxxhdpi", 8)):
        for round_icon in (False, True):
            art = Image.new("RGBA", (vw, vh), (0, 0, 0, 0))
            for y in range(vh):
                for x in range(vw):
                    if round_icon:
                        inside = (x + 0.5 - 12) ** 2 + (y + 0.5 - 12) ** 2 <= 12 ** 2
                    else:
                        corner = min(x, vw - 1 - x) + min(y, vh - 1 - y)
                        inside = corner >= 2
                    if not inside:
                        continue
                    n = c.px[vy + y][vx + x]
                    col = preview.rgb(n) if n is not None else bg
                    art.putpixel((x, y), col + (255,))
            # 1px outline ring on the shape edge
            px = art.load()
            edge = []
            for y in range(vh):
                for x in range(vw):
                    if px[x, y][3] == 0:
                        continue
                    for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                        nx, ny = x + dx, y + dy
                        if not (0 <= nx < vw and 0 <= ny < vh) or px[nx, ny][3] == 0:
                            edge.append((x, y))
                            break
            for x, y in edge:
                px[x, y] = out + (255,)
            big = art.resize((vw * s, vh * s), Image.NEAREST)
            name = "ic_launcher_round.png" if round_icon else "ic_launcher.png"
            big.save(os.path.join(RES_DIR, f"mipmap-{folder}", name))


def main() -> int:
    grids = build_all()
    problems = validate(grids)
    if problems:
        print("\n".join(problems))
        return 1
    with open(os.path.join(ART_DIR, "ScenePalettes.kt"), "w", newline="\n") as f:
        f.write(kotlin_palettes())
    with open(os.path.join(ART_DIR, "SceneArt.kt"), "w", newline="\n") as f:
        f.write(kotlin_grids(grids))
    with open(os.path.join(RES_DIR, "drawable", "ic_launcher_foreground.xml"), "w", newline="\n") as f:
        f.write(launcher_foreground(grids["INFORMANT_CREST"]))
    with open(os.path.join(RES_DIR, "drawable", "ic_launcher_monochrome.xml"), "w", newline="\n") as f:
        f.write(launcher_monochrome(grids["INFORMANT_CREST"]))
    legacy_icons(grids["INFORMANT_CREST"])
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    preview.sheet([(k, grids[k]) for k in scenes_b.SCENES], 6, 2,
                  os.path.join(PREVIEW_DIR, "scenes.png"), bg=preview.GROUND)
    preview.sheet([(k, grids[k]) for k in vignettes.VIGNETTES], 8, 2,
                  os.path.join(PREVIEW_DIR, "vignettes.png"))
    preview.sheet([("crest", grids["INFORMANT_CREST"])], 12, 1,
                  os.path.join(PREVIEW_DIR, "crest.png"), circle=True)
    print("ok:", ", ".join(grids))
    return 0


if __name__ == "__main__":
    sys.exit(main())
